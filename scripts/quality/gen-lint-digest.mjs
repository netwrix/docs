#!/usr/bin/env node
/**
 * gen-lint-digest.mjs - writes .claude/references/lint-rules.md: every rule Vale, Dale, and the
 * AI-isms check enforce, in plain language, so a writer (or the doc-draft skill) can draft
 * wording that passes the first time. Generated from the rule files, so it cannot drift.
 *
 *   node scripts/quality/gen-lint-digest.mjs           # write the file
 *   node scripts/quality/gen-lint-digest.mjs --check   # exit 1 if it is out of date
 */
import fs from 'fs';
import path from 'path';
import yaml from 'js-yaml';

const OUT = '.claude/references/lint-rules.md';
const readYml = f => yaml.load(fs.readFileSync(f, 'utf8'));
const plain = s => String(s).replace(/\\b/g, '').replace(/\\([.'()\-])/g, '$1').replace(/\(\?:/g, '(').replace(/\(\?i\)/g, '').trim();
const msg = (m, term) => String(m || '').replace(/%s/g, term ?? '<term>');

function vale() {
  const dir = '.vale/styles/Netwrix';
  const lines = [];
  for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.yml')).sort()) {
    const r = readYml(path.join(dir, f));
    const name = path.basename(f, '.yml');
    if (r.extends === 'substitution' && r.swap) {
      const pairs = Object.entries(r.swap).slice(0, 12).map(([a, b]) => `${plain(a)} → ${b}`);
      lines.push(`- **${name}**: ${msg(r.message, '<form>')} Examples: ${pairs.join('; ')}${Object.keys(r.swap).length > 12 ? '; …' : ''}`);
    } else if (r.extends === 'existence' && r.tokens) {
      const toks = r.tokens.map(plain).filter(Boolean);
      lines.push(`- **${name}**: ${msg(r.message, '<term>')} Terms: ${toks.slice(0, 40).join(', ')}${toks.length > 40 ? `, … (${toks.length} in all)` : ''}`);
    } else {
      lines.push(`- **${name}**: ${msg(r.message, '<text>')}`);
    }
  }
  return lines;
}

function dale() {
  const dir = '.claude/skills/dale/rules';
  return fs.readdirSync(dir).filter(f => f.endsWith('.yml')).sort().map(f => {
    const r = readYml(path.join(dir, f));
    return `- **${path.basename(f, '.yml')}**: ${String(r.reason).replace(/\s+/g, ' ').trim()} (Message: ${r.message})`;
  });
}

function aiisms() {
  const c = readYml('scripts/doc-draft/ai-isms.yml');
  return Object.keys(c.lexical);
}

export function build() {
  return [
    '# Lint rules at a glance',
    '',
    'Generated by `scripts/quality/gen-lint-digest.mjs` from the Vale rules, the Dale rules, and the AI-isms word list. Do not edit by hand.',
    'Read this before drafting. Each rule below is checked before a PR: Vale and the word list by code, Dale by a model.',
    '',
    '## Vale (code, every page)',
    '',
    ...vale(),
    '',
    '## Dale (model-checked)',
    '',
    ...dale(),
    '',
    '## AI-isms word list (avoid these words and phrases)',
    '',
    aiisms().join(', ') + '.',
    '',
    '## AI-writing patterns the judge looks for',
    '',
    'See `.claude/references/humanizer-rules.md`. In short: no inflated significance, no tacked-on "-ing" clauses, no promotional language, no unsourced attributions, no "not just X, but Y", no false ranges, and no synonym cycling.',
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === new URL(import.meta.url).pathname) {
  const next = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== next) { console.error(`${OUT} is out of date. Run: node scripts/quality/gen-lint-digest.mjs`); process.exit(1); }
    console.log('No drift: lint-rules.md matches the rule files.');
  } else {
    fs.writeFileSync(OUT, next);
    console.log(`wrote ${OUT} (${next.split('\n').length} lines)`);
  }
}
